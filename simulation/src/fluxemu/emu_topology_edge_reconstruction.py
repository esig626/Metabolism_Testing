"""Explicit stationary EMU motif for Phase 2A edge reconstruction.

The chemistry in this module is a deliberately synthetic test network. Its
carbon maps are declared explicitly; it is not presented as a biochemical
reaction system. Exact MIDs are never prescribed here. They are generated by
the existing COBRApy-to-mfapy bridge and :func:`run_batch_forward`.

Three alternative mapped decarboxylations feed a common two-carbon pool
``X``. A downstream mapped decarboxylation produces the one-carbon pool
``W``. The full ``X`` MID is the topology observation, while the full ``W``
MID is quarantined as a withheld prediction target.
"""

